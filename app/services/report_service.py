"""
Report generation for a completed match job.

Produces a consolidated report in two formats:
  * JSON  - the full analytics summary plus per-section stats
  * HTML  - a self-contained, styled page suitable for download/printing

The HTML uses no external assets so it renders offline.
"""

from __future__ import annotations

import html
import json
from pathlib import Path

from ..config import Settings
from ..models import MatchJob
from .analysis_service import job_output_dir


def _read_json(path: str | None) -> dict:
    if not path:
        return {}
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return {}


def build_report_data(job: MatchJob) -> dict:
    """Assemble the structured report payload for a job."""
    artifacts = job.artifacts or {}
    possession = _read_json(artifacts.get("possession_json"))
    passes = _read_json(artifacts.get("passes_json"))
    shots = _read_json(artifacts.get("shots_json"))
    goals = _read_json(artifacts.get("goals_json"))
    highlights = _read_json(artifacts.get("highlights_json"))

    return {
        "job_id": job.id,
        "match": job.original_filename,
        "generated_from": "Smart Football Match Analysis System",
        "status": job.status,
        "final_score": goals.get("final_score", {}),
        "possession": possession.get("summary", {}),
        "passes": passes.get("summary", {}),
        "shots": shots.get("summary", {}),
        "goals": {
            "total": goals.get("summary", {}).get("total", 0),
            "events": goals.get("goals", []),
        },
        "highlights": {
            "event_count": highlights.get("event_count", 0),
            "clip_count": highlights.get("clip_count", 0),
        },
    }


def render_report_html(data: dict) -> str:
    """Render the report payload to a self-contained HTML string."""

    def esc(v) -> str:
        return html.escape(str(v))

    def stat_rows(d: dict) -> str:
        if not d:
            return '<tr><td colspan="2" class="muted">No data</td></tr>'
        return "".join(
            f"<tr><td>{esc(k.replace('_', ' ').title())}</td><td>{esc(v)}</td></tr>"
            for k, v in d.items()
            if not isinstance(v, (dict, list))
        )

    score = data.get("final_score", {})
    score_line = " — ".join(f"{esc(k)} {esc(v)}" for k, v in score.items()) or "N/A"

    goal_items = data.get("goals", {}).get("events", [])
    goals_html = "".join(
        f"<li><strong>{esc(g.get('scoring_team', '?'))}</strong> "
        f"(#{esc(g.get('scorer_track_id', '?'))}) at "
        f"{esc(round(g.get('timestamp_sec', 0), 1))}s — "
        f"{esc(g.get('scoreline', ''))}</li>"
        for g in goal_items
    ) or '<li class="muted">No goals detected</li>'

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Match Report — {esc(data.get('match', ''))}</title>
<style>
  :root {{ --bg:#0f1419; --card:#1a2029; --accent:#22c55e; --text:#e6edf3; --muted:#8b98a5; }}
  * {{ box-sizing:border-box; }}
  body {{ margin:0; font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;
         background:var(--bg); color:var(--text); padding:32px; }}
  h1 {{ margin:0 0 4px; font-size:26px; }}
  .sub {{ color:var(--muted); margin-bottom:24px; }}
  .score {{ font-size:34px; font-weight:700; color:var(--accent); margin:12px 0 28px; }}
  .grid {{ display:grid; grid-template-columns:repeat(auto-fit,minmax(260px,1fr)); gap:16px; }}
  .card {{ background:var(--card); border:1px solid #2a323d; border-radius:12px; padding:18px; }}
  .card h2 {{ margin:0 0 12px; font-size:15px; text-transform:uppercase; letter-spacing:.06em;
             color:var(--muted); }}
  table {{ width:100%; border-collapse:collapse; font-size:14px; }}
  td {{ padding:6px 4px; border-bottom:1px solid #232a33; }}
  td:last-child {{ text-align:right; font-variant-numeric:tabular-nums; }}
  ul {{ margin:0; padding-left:18px; font-size:14px; line-height:1.7; }}
  .muted {{ color:var(--muted); }}
  footer {{ margin-top:28px; color:var(--muted); font-size:12px; }}
</style>
</head>
<body>
  <h1>Match Analysis Report</h1>
  <div class="sub">{esc(data.get('match', ''))} · job {esc(data.get('job_id', ''))}</div>
  <div class="score">{score_line}</div>
  <div class="grid">
    <div class="card"><h2>Possession</h2><table>{stat_rows(data.get('possession', {}))}</table></div>
    <div class="card"><h2>Passing</h2><table>{stat_rows(data.get('passes', {}))}</table></div>
    <div class="card"><h2>Shots</h2><table>{stat_rows(data.get('shots', {}))}</table></div>
    <div class="card"><h2>Goals</h2><ul>{goals_html}</ul></div>
  </div>
  <footer>Generated by the Smart Football Match Analysis System.</footer>
</body>
</html>
"""


def write_report(settings: Settings, job: MatchJob, fmt: str = "html") -> Path:
    """Write the report to the job's output dir and return its path."""
    out = job_output_dir(settings, job.id)
    out.mkdir(parents=True, exist_ok=True)
    data = build_report_data(job)

    if fmt == "json":
        path = out / "report.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
        return path

    path = out / "report.html"
    with open(path, "w", encoding="utf-8") as f:
        f.write(render_report_html(data))
    return path
